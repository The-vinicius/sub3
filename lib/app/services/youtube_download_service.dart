import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:path_provider/path_provider.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:youtube_explode_dart/youtube_explode_dart.dart';

const _prefsYtDlpPathKey = 'ytdlp_binary_path';

/// Opção de legenda para o dropdown (desktop e Android).
class SubtitleTrackOption {
  const SubtitleTrackOption({
    required this.languageCode,
    required this.label,
    required this.useAutoGeneratedCaption,
  });

  final String languageCode;
  final String label;

  /// Desktop: controla `--write-subs` vs `--write-auto-subs`. Android: filtra faixa CC.
  final bool useAutoGeneratedCaption;
}

/// Título + opções de legenda (um pedido agregado no desktop via `yt-dlp -J`).
class YoutubeVideoMetadata {
  const YoutubeVideoMetadata({
    required this.title,
    required this.subtitleTracks,
  });

  final String title;
  final List<SubtitleTrackOption> subtitleTracks;
}

/// Resultado de download pronto para gravar na BD como [Sub].
class YoutubeDownloadResult {
  YoutubeDownloadResult({
    required this.displayTitle,
    required this.audioFile,
    required this.subtitleFile,
  });

  final String displayTitle;
  final File audioFile;
  final File subtitleFile;
}

/// Importação híbrida: **yt-dlp** em desktop e **youtube_explode_dart** em Android.
class YoutubeDownloadService {
  YoutubeDownloadService();

  /// iOS não está incluído (política/rede); Web não suportada.
  static bool get isImportSupported =>
      Platform.isAndroid ||
      Platform.isLinux ||
      Platform.isMacOS ||
      Platform.isWindows;

  static bool get _isDesktop =>
      Platform.isLinux || Platform.isMacOS || Platform.isWindows;

  static bool get _isAndroid => Platform.isAndroid;

  Future<String> _ytDlpExecutable() async {
    final prefs = await SharedPreferences.getInstance();
    final custom = prefs.getString(_prefsYtDlpPathKey)?.trim();
    if (custom != null && custom.isNotEmpty) {
      return custom;
    }
    return Platform.isWindows ? 'yt-dlp.exe' : 'yt-dlp';
  }

  static Future<void> setYtDlpBinaryPath(String? path) async {
    final prefs = await SharedPreferences.getInstance();
    if (path == null || path.trim().isEmpty) {
      await prefs.remove(_prefsYtDlpPathKey);
    } else {
      await prefs.setString(_prefsYtDlpPathKey, path.trim());
    }
  }

  static Future<String?> getYtDlpBinaryPath() async {
    final prefs = await SharedPreferences.getInstance();
    return prefs.getString(_prefsYtDlpPathKey);
  }

  /// Valida URL ou ID do YouTube (usa o mesmo parser que o explode).
  static String? tryParseVideoId(String urlOrId) =>
      VideoId.parseVideoId(urlOrId.trim());

  /// Metadados para o diálogo (título + legendas) com o mínimo de pedidos à rede.
  Future<YoutubeVideoMetadata> getVideoMetadata(String urlOrId) async {
    final id = tryParseVideoId(urlOrId);
    if (id == null) {
      throw ArgumentError('URL ou ID do YouTube inválido.');
    }
    if (_isDesktop) {
      return _metadataYtDlp(urlOrId.trim());
    }
    if (_isAndroid) {
      final yt = YoutubeExplode();
      try {
        final video = await yt.videos.get(VideoId(id));
        final manifest = await yt.videos.closedCaptions.getManifest(video.id);
        return YoutubeVideoMetadata(
          title: video.title,
          subtitleTracks: _androidTracksFromManifest(manifest),
        );
      } finally {
        yt.close();
      }
    }
    throw UnsupportedError('Importação YouTube não suportada nesta plataforma.');
  }

  /// Lista idiomas / tipos de legenda disponíveis.
  Future<List<SubtitleTrackOption>> listSubtitleTracks(String urlOrId) async {
    return (await getVideoMetadata(urlOrId)).subtitleTracks;
  }

  /// Obtém título do vídeo (para nome por defeito).
  Future<String> resolveTitle(String urlOrId) async {
    return (await getVideoMetadata(urlOrId)).title;
  }

  /// Descarrega áudio + legenda para `ApplicationDocumentsDirectory/youtube_imports/<id>/`.
  Future<YoutubeDownloadResult> download({
    required String urlOrId,
    required SubtitleTrackOption subtitle,
    String? displayNameOverride,
  }) async {
    final id = tryParseVideoId(urlOrId);
    if (id == null) {
      throw ArgumentError('URL ou ID do YouTube inválido.');
    }
    final base = await getApplicationDocumentsDirectory();
    final outDir = Directory(p.join(base.path, 'youtube_imports', id));
    await outDir.create(recursive: true);

    final title = displayNameOverride?.trim().isNotEmpty == true
        ? displayNameOverride!.trim()
        : await resolveTitle(urlOrId);
    final safe = _sanitizeBaseName(title);

    if (_isDesktop) {
      return _downloadYtDlp(
        url: urlOrId.trim(),
        subtitle: subtitle,
        outDir: outDir,
        safeBase: safe,
        displayTitle: title,
      );
    }
    if (_isAndroid) {
      return _downloadExplode(
        videoId: id,
        subtitle: subtitle,
        outDir: outDir,
        safeBase: safe,
        displayTitle: title,
      );
    }
    throw UnsupportedError('Importação YouTube não suportada nesta plataforma.');
  }

  // --- Desktop: yt-dlp ---

  Future<Map<String, dynamic>> _ytDlpDumpJson(String url) async {
    final bin = await _ytDlpExecutable();
    final r = await Process.run(bin, [
      '-J',
      '--skip-download',
      '--no-playlist',
      '--no-warnings',
      url,
    ], runInShell: false);
    if (r.exitCode != 0) {
      final err = (r.stderr as String).trim();
      throw StateError(
        err.isNotEmpty ? err : 'yt-dlp falhou (código ${r.exitCode}).',
      );
    }
    final raw = (r.stdout as String).trim();
    if (raw.isEmpty) {
      throw StateError('yt-dlp não devolveu metadados.');
    }
    try {
      return json.decode(raw) as Map<String, dynamic>;
    } catch (_) {
      throw StateError('Resposta JSON inválida do yt-dlp.');
    }
  }

  List<SubtitleTrackOption> _parseSubsFromYtDlpJson(Map<String, dynamic> j) {
    final manual = j['subtitles'] as Map<String, dynamic>?;
    final auto = j['automatic_captions'] as Map<String, dynamic>?;
    final options = <SubtitleTrackOption>[];
    if (manual != null) {
      for (final code in manual.keys) {
        options.add(
          SubtitleTrackOption(
            languageCode: code,
            label: '$code (manual)',
            useAutoGeneratedCaption: false,
          ),
        );
      }
    }
    if (auto != null) {
      for (final code in auto.keys) {
        options.add(
          SubtitleTrackOption(
            languageCode: code,
            label: '$code (automático)',
            useAutoGeneratedCaption: true,
          ),
        );
      }
    }
    options.sort((a, b) => a.label.compareTo(b.label));
    return options;
  }

  Future<YoutubeVideoMetadata> _metadataYtDlp(String url) async {
    final j = await _ytDlpDumpJson(url);
    final t = (j['title'] as String?)?.trim();
    final title =
        (t == null || t.isEmpty) ? (j['id'] as String? ?? 'video') : t;
    return YoutubeVideoMetadata(
      title: title,
      subtitleTracks: _parseSubsFromYtDlpJson(j),
    );
  }

  static List<SubtitleTrackOption> _androidTracksFromManifest(
    ClosedCaptionManifest manifest,
  ) {
    final sorted = [...manifest.tracks]..sort((a, b) {
      int rank(ClosedCaptionFormat f) {
        if (f == ClosedCaptionFormat.vtt) return 0;
        if (f == ClosedCaptionFormat.srv3) return 1;
        return 2;
      }

      return rank(a.format).compareTo(rank(b.format));
    });
    final seen = <String>{};
    final out = <SubtitleTrackOption>[];
    for (final t in sorted) {
      if (t.format != ClosedCaptionFormat.vtt &&
          t.format != ClosedCaptionFormat.srv3) {
        continue;
      }
      final key = '${t.language.code}|${t.isAutoGenerated}';
      if (seen.add(key)) {
        out.add(
          SubtitleTrackOption(
            languageCode: t.language.code,
            label:
                '${t.language.name} (${t.language.code})'
                '${t.isAutoGenerated ? ' — automático' : ''}',
            useAutoGeneratedCaption: t.isAutoGenerated,
          ),
        );
      }
    }
    out.sort((a, b) => a.label.compareTo(b.label));
    return out;
  }

  Future<YoutubeDownloadResult> _downloadYtDlp({
    required String url,
    required SubtitleTrackOption subtitle,
    required Directory outDir,
    required String safeBase,
    required String displayTitle,
  }) async {
    final bin = await _ytDlpExecutable();
    final args = <String>[
      '--no-playlist',
      '-f',
      'bestaudio/best',
      '-x',
      '--audio-format',
      'mp3',
      if (subtitle.useAutoGeneratedCaption) '--write-auto-subs' else '--write-subs',
      '--sub-langs',
      subtitle.languageCode,
      '--convert-subs',
      'srt',
      '-o',
      p.join(outDir.path, '$safeBase.%(ext)s'),
      url,
    ];
    final r = await Process.run(
      bin,
      args,
      workingDirectory: outDir.path,
    );
    if (r.exitCode != 0) {
      final err = (r.stderr as String).trim();
      throw StateError(
        err.isNotEmpty ? err : 'yt-dlp falhou ao descarregar (código ${r.exitCode}).',
      );
    }

    final lang = subtitle.languageCode.toLowerCase();
    File? mp3;
    File? srt;
    for (final e in outDir.listSync().whereType<File>()) {
      final n = p.basename(e.path).toLowerCase();
      if (n.endsWith('.mp3')) {
        mp3 ??= e;
      }
      if (n.endsWith('.srt')) {
        if (n.contains('.$lang.') || n.endsWith('.$lang.srt')) {
          srt = e;
        } else {
          srt ??= e;
        }
      }
    }
    if (mp3 == null || !mp3.existsSync()) {
      throw StateError('Ficheiro de áudio .mp3 não encontrado após yt-dlp.');
    }
    if (srt == null || !srt.existsSync()) {
      throw StateError(
        'Legenda .srt não encontrada. Experimente outro idioma ou tipo (manual/automático).',
      );
    }
    return YoutubeDownloadResult(
      displayTitle: displayTitle,
      audioFile: mp3,
      subtitleFile: srt,
    );
  }

  // --- Android: youtube_explode_dart ---

  ClosedCaptionTrackInfo? _pickAndroidTrack(
    ClosedCaptionManifest manifest,
    SubtitleTrackOption subtitle,
  ) {
    final candidates = manifest.tracks.where(
      (t) =>
          t.language.code.toLowerCase() ==
              subtitle.languageCode.toLowerCase() &&
          t.isAutoGenerated == subtitle.useAutoGeneratedCaption &&
          (t.format == ClosedCaptionFormat.vtt ||
              t.format == ClosedCaptionFormat.srv3),
    );
    return candidates.isEmpty ? null : candidates.first;
  }

  Future<YoutubeDownloadResult> _downloadExplode({
    required String videoId,
    required SubtitleTrackOption subtitle,
    required Directory outDir,
    required String safeBase,
    required String displayTitle,
  }) async {
    final yt = YoutubeExplode();
    try {
      final video = await yt.videos.get(VideoId(videoId));
      final streamManifest = await yt.videos.streams.getManifest(video.id);
      if (streamManifest.audioOnly.isEmpty) {
        throw StateError('Nenhum stream de áudio disponível para este vídeo.');
      }
      final audioInfo = streamManifest.audioOnly.withHighestBitrate();
      final audioPath = p.join(outDir.path, '$safeBase.${audioInfo.container.name}');
      final audioFile = File(audioPath);
      final sink = audioFile.openWrite();
      await for (final chunk in yt.videos.streams.get(audioInfo)) {
        sink.add(chunk);
      }
      await sink.flush();
      await sink.close();

      final ccManifest = await yt.videos.closedCaptions.getManifest(video.id);
      final trackInfo = _pickAndroidTrack(ccManifest, subtitle);
      if (trackInfo == null) {
        throw StateError(
          'Legenda não disponível para ${subtitle.languageCode} '
          '(${subtitle.useAutoGeneratedCaption ? 'automático' : 'manual'}).',
        );
      }
      final track = await yt.videos.closedCaptions.get(trackInfo);
      final srtBody = _closedCaptionsToSrt(track);
      final subPath = p.join(outDir.path, '$safeBase.${subtitle.languageCode}.srt');
      final subtitleFile = File(subPath);
      await subtitleFile.writeAsString(srtBody, flush: true);

      return YoutubeDownloadResult(
        displayTitle: displayTitle,
        audioFile: audioFile,
        subtitleFile: subtitleFile,
      );
    } finally {
      yt.close();
    }
  }
}

String _closedCaptionsToSrt(ClosedCaptionTrack track) {
  final sb = StringBuffer();
  var i = 1;
  for (final c in track.captions) {
    sb.writeln(i++);
    sb.writeln('${_fmtSrt(c.offset)} --> ${_fmtSrt(c.end)}');
    sb.writeln(_stripSimpleHtml(c.text).replaceAll('\n', ' ').trim());
    sb.writeln();
  }
  return sb.toString();
}

String _fmtSrt(Duration d) {
  final h = d.inHours.toString().padLeft(2, '0');
  final m = d.inMinutes.remainder(60).toString().padLeft(2, '0');
  final s = d.inSeconds.remainder(60).toString().padLeft(2, '0');
  final ms = d.inMilliseconds.remainder(1000).toString().padLeft(3, '0');
  return '$h:$m:$s,$ms';
}

String _stripSimpleHtml(String s) =>
    s.replaceAll(RegExp(r'<[^>]*>'), '').replaceAll('&nbsp;', ' ').trim();

String _sanitizeBaseName(String title) {
  var s = title
      .replaceAll(RegExp(r'[\\/:*?"<>|]'), '')
      .replaceAll(RegExp(r'\s+'), '_')
      .trim();
  if (s.isEmpty) {
    s = 'video';
  }
  if (s.length > 80) {
    s = s.substring(0, 80);
  }
  return s;
}
